// Обезличивание контрагентов (ТЗ-доп. §3): полные ИНН/названия не сохраняются.
// Отчёт 3.3 (минимальная правка): датасет организаторов УЖЕ обезличен на источнике —
// названия вида «ООО «Элеватор-242»» и ИНН с префиксом «00». Старая маска
// «первые 2 символа + ***» сводит все такие ООО к ОО*** (а ИНН — к 100 вариантам),
// теряя уникальность. Поэтому:
//  - похоже на уже обезличенное (ООО/АО/ПАО/ИП + цифра в названии; ИНН 00…) → вернуть как есть;
//  - реальное (ещё не обезличенное) значение → маскировать с сохранением уникальности:
//    короткий детерминированный хэш (djb2 → base36, 4 знака) добавляет различимость —
//    разные имена с одинаковым префиксом дают разные маски.

const ANON_NAME_RE = /^(ООО|ПАО|ЗАО|АО|ИП|НП|ТОО)\s+[«'"]?[А-ЯЁA-Zа-яё0-9]+.*\d/i;

/** Короткий детерминированный хэш (djb2 → base36, 4 знака). Не крипто, только различимость масок. */
function hash4(s) {
  let h = 5381;
  for (let i = 0; i < s.length; i++) h = ((h << 5) + h + s.charCodeAt(i)) >>> 0;
  return (h % 1_679_616).toString(36).padStart(4, '0');
}

/**
 * Маска названия контрагента.
 * Уже обезличенное имя (юр. префикс + цифра в названии) возвращается без изменений —
 * его уникальность (Элеватор-242 ≠ Элеватор-305) не нужно терять.
 * Реальное имя → первые 2 символа + *** + короткий хэш (уникальность сохранена).
 */
export function maskName(name) {
  if (!name) return null;
  const clean = String(name).trim();
  if (!clean) return null;
  if (ANON_NAME_RE.test(clean)) return clean; // данные уже обезличены на источнике
  if (clean.length <= 2) return `${clean[0] ?? ''}***`;
  return `${clean.slice(0, 2)}***${hash4(clean)}`;
}

/**
 * Маска ИНН. Синтетические/обезличенные ИНН датасета начинаются с «00» —
 * вернуть как есть (их различают последние цифры; старая маска давала лишь 100 вариантов
 * на весь справочник). Реальные ИНН → первые 2 + *** + хэш + последние 2
 * (innSuffix() продолжает читать хвост).
 */
export function maskInn(inn) {
  if (!inn) return null;
  const raw = String(inn).trim();
  const digits = raw.replace(/\D/g, '');
  if (digits.length < 4) return null;
  if (digits.startsWith('00')) return digits; // уже обезличенный (синтетический) ИНН
  if (raw.includes('*')) return raw; // уже маскированный — идемпотентность
  return `${digits.slice(0, 2)}***${hash4(digits)}${digits.slice(-2)}`;
}

// Последние 2 видимые цифры маскированного ИНН ("77******12" → "12")
export function innSuffix(innMasked) {
  if (!innMasked) return null;
  const m = String(innMasked).match(/(\d{2})$/);
  return m ? m[1] : null;
}
